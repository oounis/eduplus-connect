#!/usr/bin/env node
/**
 * Pulls the shared Kogia visual package into this app. EduPlus Connect is a
 * Kogia World product: its mark, tiles, account levels, loaders, avatars and
 * icons come from the two company sources (brand/ and visual-assets/ in the
 * kogia-group repository) and are never drawn here by hand.
 *
 *   KOGIA_ROOT=/path/to/kogia-group node scripts/sync-kogia-assets.mjs
 *
 * Output (committed, so the build never depends on the other repository):
 *   public/kogia/{tile,mark,mark-white}.svg, tiers/*.svg, loaders/*.svg,
 *   avatars/*.png, src/components/kogia-icon-paths.ts
 */
import { copyFile, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = process.env.KOGIA_ROOT ?? "/mnt/c/Current LAB/KogiaGroup";
const LANE = "eduplus";
// The EduPlus lane, as declared in visual-assets/tokens/product-colors.css.
const COLORS = { 50: "#EEF4FF", 300: "#8EAEFF", 600: "#223DE7", 700: "#1C2FD4" };
const fixLane = (svg) =>
  svg
    .replace(/var\(--kg-accent-600,[^)]*\)/g, COLORS[600])
    .replace(/var\(--kg-accent-700,[^)]*\)/g, COLORS[700])
    .replace(/var\(--kg-accent-300,[^)]*\)/g, COLORS[300])
    .replace(/var\(--kg-accent-50,[^)]*\)/g, COLORS[50]);

const OUT = resolve("public/kogia");
for (const d of ["", "tiers", "loaders", "avatars"]) await mkdir(resolve(OUT, d), { recursive: true });

await copyFile(resolve(ROOT, `brand/marque/tile/kogia-tile-${LANE}.svg`), resolve(OUT, "tile.svg"));
await copyFile(resolve(ROOT, `brand/marque/mark/kogia-mark-${LANE}.svg`), resolve(OUT, "mark.svg"));
await copyFile(resolve(ROOT, "brand/marque/mark/kogia-mark-white.svg"), resolve(OUT, "mark-white.svg"));

for (const tier of ["amateur", "pro", "expert"]) {
  await copyFile(resolve(ROOT, `brand/marque/tiers/${LANE}/kogia-tier-${tier}.svg`), resolve(OUT, `tiers/${tier}.svg`));
}
const loaders = [];
for (const f of (await readdir(resolve(ROOT, "brand/marque/loaders"))).filter((f) => f.endsWith(".svg"))) {
  const name = f.replace(/^kogia-loader-/, "").replace(/\.svg$/, "");
  await writeFile(resolve(OUT, `loaders/${name}.svg`), fixLane(await readFile(resolve(ROOT, "brand/marque/loaders", f), "utf8")));
  loaders.push(name);
}
const avatars = [];
for (const f of (await readdir(resolve(ROOT, "visual-assets/avatars/png"))).filter((f) => f.endsWith(".png")).sort()) {
  await copyFile(resolve(ROOT, "visual-assets/avatars/png", f), resolve(OUT, "avatars", f));
  avatars.push(f.replace(/\.png$/, ""));
}

// Icons: inner SVG content, rendered by <KogiaIcon>, colour from currentColor.
const icons = {};
for (const f of (await readdir(resolve(ROOT, "visual-assets/icons/svg"))).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = await readFile(resolve(ROOT, "visual-assets/icons/svg", f), "utf8");
  icons[f.replace(/^kg-/, "").replace(/\.svg$/, "")] = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "")
    .replace(/<title[^>]*>[\s\S]*?<\/title>/g, "")
    .replace(/var\(--kg-icon-accent[^)]*\)/g, "currentColor")
    .replace(/\s+/g, " ").trim();
}
await writeFile(
  resolve("src/components/kogia-icon-paths.ts"),
  `// GENERATED by scripts/sync-kogia-assets.mjs from kogia-group/visual-assets/icons/svg. Do not edit.\n` +
    `export const KOGIA_ICONS = ${JSON.stringify(icons, null, 2)} as const;\n` +
    `export type KogiaIconName = keyof typeof KOGIA_ICONS;\n` +
    `export const KOGIA_AVATARS = ${JSON.stringify(avatars)} as const;\n` +
    `export const KOGIA_LOADERS = ${JSON.stringify(loaders)} as const;\n`,
);
console.log(`Kogia package synced: ${Object.keys(icons).length} icons, ${avatars.length} avatars, ${loaders.length} loaders, 3 tiers, tile + marks (lane ${LANE}).`);
